"""(techno-engines) ACID's tables (firmware/src/acid/eng_acid_tables.h): the ATEK303 voice's laws (animatek/FM1-Animatek,
atek303/app/dsp/atek_voice.c, GPL-3.0-or-later, Javier Melgar / Animatek; Open303's parts by Robin Schmidt, MIT) worked out
here in float, once, so that the firmware runs them in integers. Needs numpy and scipy (the decimators).
    python3 tools/gen_acid_tables.py > firmware/src/acid/eng_acid_tables.h
"""
import math
import numpy as np
from scipy import signal

SR = 44100.0
import os
OS = int(os.environ.get("ACID_OS", "2"))   # the oversampling the voice runs at (ATEK303: 4)
SR4 = SR * OS
VT = 1.2
MAX_CUTOFF_HZ = 14000.0
DECAY_T_OVER_TAU = 2.302585093


def arr(name, ctype, vals, per=12, comment=""):
    s = f"static const {ctype} {name}[{len(vals)}] = {{   /* {comment} */\n"
    for i in range(0, len(vals), per):
        s += "    " + ", ".join(str(int(v)) for v in vals[i:i + per]) + ",\n"
    return s + "};\n"


out = []
out.append("/* SPDX-License-Identifier: GPL-3.0-or-later */\n/* generated by tools/gen_acid_tables.py: do not edit */\n")
def q31(x):
    return round(x * (1 << 31))
consts = {
    "ACID_OS": OS,
    "ACID_HP1_B0": q31(0.5 * (1 + math.exp(-2 * math.pi * 44.486 / SR4))),   # Open303's 44.5 Hz high-pass, at OS x
    "ACID_HP1_A": q31(math.exp(-2 * math.pi * 44.486 / SR4)),
    "ACID_FBHP": q31(math.exp(-2 * math.pi * 150.0 / SR4)),                  # the feedback's 150 Hz high-pass
    "ACID_LP_SAW": q31(1 - math.exp(-2 * math.pi * min(1 / (2 * math.pi * 20e-6), 0.45 * SR4) / SR4)),   # reset 20 us
    "ACID_LP_SQ": q31(1 - math.exp(-2 * math.pi * min(1 / (2 * math.pi * 5e-6), 0.45 * SR4) / SR4)),     # slew 5 us
    "ACID_HP_SAW": q31(math.exp(-2 * math.pi * 15.0 / SR4)),                  # the droops: 15 Hz, 60 Hz
    "ACID_HP_SQ": q31(math.exp(-2 * math.pi * 60.0 / SR4)),
}
for k, v in consts.items():
    out.append(f"#define {k} {v}\n")

# the diode: VT tanh(x / VT), x in Q16 (1.0 = 65536); the table over |x| = 0 .. 6.0 (DIODE_N steps), Q16 values
DN = 384
DSTEP = 6.0 / DN
out.append(f"#define ACID_DIODE_N {DN}\n#define ACID_DIODE_SHIFT 10   /* x (Q16) >> 10: 1/64 a step: 6.0 = {DN} steps */\n")
assert abs(DSTEP - 1 / 64) < 1e-12
out.append(arr("ACID_DIODE", "int32_t", [round(65536 * VT * math.tanh(i * DSTEP / VT)) for i in range(DN + 1)],
               comment="VT tanh(x / VT), Q16, x = i / 64"))

# tanh(u), u in Q16, over 0 .. 8 (1/32 a step): the OTA and the output's saturation
out.append(arr("ACID_TANH", "int32_t", [round(65536 * math.tanh(i / 32)) for i in range(257)], comment="tanh(i / 32), Q16"))

# the filter's coefficients against log2 of the cutoff (Hz): from 10 Hz, 1/32 octave a step, to MAX_CUTOFF_HZ
LO = math.log2(10.0)
NC = int(math.ceil((math.log2(MAX_CUTOFF_HZ) - LO) * 32)) + 1
out.append(f"#define ACID_LC0 {round(LO * 65536)}   /* log2(10 Hz), Q16 */\n#define ACID_NC {NC}   /* entries, 1/32 octave each */\n")
b0s, ks = [], []
for i in range(NC):
    fc = min(2 ** (LO + i / 32), MAX_CUTOFF_HZ, 0.45 * SR4)
    fx = fc / (SR4 * 1.4142135623730951)
    b0 = (0.00045522346 + 6.1922189 * fx) / (1.0 + 12.358354 * fx + 4.4156345 * fx * fx)
    k = fx * (fx * (fx * (fx * (fx * (fx + 7198.6997) - 5837.7917) - 476.47308) + 614.95611) + 213.87126) + 16.998792
    b0s.append(round(b0 * (1 << 24)))
    ks.append(round(k * 1024))
out.append(arr("ACID_B0", "uint32_t", b0s, 10, "b0, Q24"))
out.append(arr("ACID_KS", "uint16_t", ks, 12, "k_scale, Q10"))

# DECAY 0..127 -> the filter envelope's factor a sample, Q31: the schematic's T 200 ms .. 2.5 s (tau = T / 2.3)
lo, hi = 200 / DECAY_T_OVER_TAU, 2500 / DECAY_T_OVER_TAU
out.append(arr("ACID_MAINC", "uint32_t",
               [round((1 << 31) * math.exp(-1.0 / (0.001 * lo * (hi / lo) ** (k / 127) * SR))) for k in range(128)], 8,
               "exp(-1 / (tau SR)), Q31"))

# the half-band decimators (4x -> 2x -> 1x), symmetric, odd length, Q15
def halfband(n, beta):
    """a windowed-sinc half-band (Kaiser): its cut at a quarter of the rate, so every other tap is zero, the centre 1/2"""
    return signal.firwin(n, 0.25, window=("kaiser", beta), fs=1.0)
stages = [("2", halfband(51, 7.0), SR * 2)] if OS == 2 else [("1", halfband(19, 7.0), SR4), ("2", halfband(51, 7.0), SR * 2)]
for name, h, fs in stages:
    w, H = signal.freqz(h, worN=8192, fs=fs)
    pb = 20 * np.log10(np.abs(H[w <= 18000]) + 1e-12)
    sb = 20 * np.log10(np.abs(H[w >= fs / 2 - 18000]) + 1e-12)
    out.append(f"/* stage {name} ({len(h)} taps at {fs:.0f} Hz): passband to 18 kHz within {pb.max():+.3f} / {pb.min():+.3f} dB, "
               f"what folds below 18 kHz at {sb.max():.1f} dB */\n")
    c = (len(h) - 1) // 2
    out.append(f"#define ACID_HB{name}_N {len(h)}\n")
    out.append(arr(f"ACID_HB{name}", "int16_t", [round(h[c - 1 - 2 * j] * 32768) for j in range((c + 1) // 2)], 12,
                   "the odd taps, from the centre out (the centre one: 1/2)"))
print("".join(out), end="")
