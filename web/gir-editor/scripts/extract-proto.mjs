// Gir Editor: the original Skiff editor's protocol section (web/editor.html, between /*PROTO-BEGIN*/ and /*PROTO-END*/)
// as an ES module, every top-level name exported. The same code as the original editor (and as web/test_web.mjs
// tests), so Gir Editor sends the very frames, and reads and writes the very files, it does.
//   node scripts/extract-proto.mjs   ->  src/lib/legacy/proto.js (generated; not committed)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(HERE, "../../editor.html"), "utf8");
const a = html.indexOf("/*PROTO-BEGIN*/"), b = html.indexOf("/*PROTO-END*/");
if (a < 0 || b < a) throw new Error("editor.html: no PROTO-BEGIN / PROTO-END section");
const src = html.slice(a, b);
const names = new Set();
for (const m of src.matchAll(/^(?:async\s+)?(?:function\*?|class|const|let)\s+([A-Za-z_$][\w$]*)/gm)) names.add(m[1]);
const out = `// GENERATED by scripts/extract-proto.mjs from web/editor.html (Skiff editor, GPL-3.0-only,
// Copyright (C) 2026 Leo Kuroshita (@kurogedelic), Hügelton Instruments; illuminus5 (Skiff)). Do not edit.
/* eslint-disable */
// @ts-nocheck
${src}
export { ${[...names].join(", ")} };
`;
writeFileSync(join(HERE, "../src/lib/legacy/proto.js"), out);
// its types: loose on purpose (the typed layer is src/lib/protocol)
writeFileSync(join(HERE, "../src/lib/legacy/proto.d.ts"), "// GENERATED by scripts/extract-proto.mjs. Do not edit.\n" +
  [...names].sort().map((n) => `export declare const ${n}: any;`).join("\n") + "\n");
console.log(`proto: ${names.size} names, ${src.split("\n").length} lines -> src/lib/legacy/proto.js`);
